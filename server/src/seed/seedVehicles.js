export const seedVehiclesIfEmpty = async () => {
  try {
    const count = await Vehicle.count();
    if (count === 0) {
      console.log('🔄 Seeding Real Fleet Vehicles with RC Book, Insurance & Mileage into database...');
      for (const item of REAL_VEHICLE_FLEET) {
        await Vehicle.create(item);
      }
      console.log(`✅ Successfully seeded ${REAL_VEHICLE_FLEET.length} vehicles into database!`);
    } else {
      console.log(`ℹ️ Vehicle table already has ${count} records in database.`);
    }
  } catch (error) {
    console.error('❌ Failed to seed vehicles:', error);
  }
};
