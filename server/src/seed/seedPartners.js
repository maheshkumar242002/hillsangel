export async function seedPartnersIfEmpty() {
  try {
    const count = await PartnerTieup.count();
    if (count === 0) {
      console.log('[Seed] Seeding realistic sample partners for Cottages, Hotels, and Food tie-ups...');
      await PartnerTieup.bulkCreate(samplePartners);
      console.log(`[Seed] ✅ Seeded ${samplePartners.length} partner tie-ups.`);
    }
  } catch (err) {
    console.warn('[Seed] Warning during partner tie-ups check/seed:', err.message);
  }
}
